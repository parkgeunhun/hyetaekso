CREATE TABLE IF NOT EXISTS manufacturers (id VARCHAR(64) PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS carriers (id VARCHAR(64) PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS categories (id VARCHAR(64) PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS products (
 id VARCHAR(64) PRIMARY KEY, manufacturer_id VARCHAR(64) NOT NULL, name VARCHAR(160) NOT NULL,
 description TEXT NOT NULL, image VARCHAR(1000) NOT NULL, status VARCHAR(20) NOT NULL,
 sort_order INTEGER NOT NULL, sample INTEGER NOT NULL, closed INTEGER NOT NULL,
 FOREIGN KEY(manufacturer_id) REFERENCES manufacturers(id)
);
CREATE TABLE IF NOT EXISTS product_categories (
 product_id VARCHAR(64) NOT NULL, category_id VARCHAR(64) NOT NULL, PRIMARY KEY(product_id,category_id),
 FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE,
 FOREIGN KEY(category_id) REFERENCES categories(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS capacities (
 id VARCHAR(64) PRIMARY KEY, product_id VARCHAR(64) NOT NULL, name VARCHAR(40) NOT NULL, price INTEGER NOT NULL,
 UNIQUE(product_id,name), FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS colors (
 id VARCHAR(64) PRIMARY KEY, product_id VARCHAR(64) NOT NULL, name VARCHAR(50) NOT NULL, image VARCHAR(1000) NOT NULL,
 UNIQUE(product_id,name), FOREIGN KEY(product_id) REFERENCES products(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS plans (
 id VARCHAR(64) PRIMARY KEY, carrier_id VARCHAR(64) NOT NULL, name VARCHAR(160) NOT NULL, fee INTEGER NOT NULL,
 enabled INTEGER NOT NULL, source_key VARCHAR(160) NOT NULL, UNIQUE(carrier_id,name,fee),
 FOREIGN KEY(carrier_id) REFERENCES carriers(id)
);
CREATE TABLE IF NOT EXISTS offers (
 id VARCHAR(64) PRIMARY KEY, capacity_id VARCHAR(64) NOT NULL, plan_id VARCHAR(64) NOT NULL,
 join_type VARCHAR(20) NOT NULL, extra INTEGER NOT NULL, source_key VARCHAR(160) NOT NULL,
 UNIQUE(capacity_id,plan_id,join_type), FOREIGN KEY(capacity_id) REFERENCES capacities(id) ON DELETE CASCADE,
 FOREIGN KEY(plan_id) REFERENCES plans(id)
);
CREATE TABLE IF NOT EXISTS supports (
 id VARCHAR(64) PRIMARY KEY, offer_id VARCHAR(64) NOT NULL, mode VARCHAR(16) NOT NULL, amount INTEGER NOT NULL,
 source VARCHAR(200) NOT NULL, updated_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, signature VARCHAR(64) NOT NULL,
 UNIQUE(offer_id,mode), FOREIGN KEY(offer_id) REFERENCES offers(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS leads (
 id VARCHAR(64) PRIMARY KEY, receipt VARCHAR(64) NOT NULL UNIQUE, request_key VARCHAR(64) NOT NULL UNIQUE,
 service VARCHAR(60) NOT NULL, name VARCHAR(80) NOT NULL, phone VARCHAR(20) NOT NULL, birth VARCHAR(10) NOT NULL,
 details TEXT NOT NULL, status VARCHAR(20) NOT NULL, notes TEXT NOT NULL,
 quote LONGTEXT NOT NULL, consent LONGTEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS banners (
 id VARCHAR(64) PRIMARY KEY, title VARCHAR(160) NOT NULL, body TEXT NOT NULL, alt VARCHAR(300) NOT NULL,
 image VARCHAR(1000) NOT NULL, mobile VARCHAR(1000) NOT NULL, link VARCHAR(1000) NOT NULL, kind VARCHAR(16) NOT NULL,
 fit VARCHAR(16) NOT NULL, intro INTEGER NOT NULL, enabled INTEGER NOT NULL, sort_order INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS content (
 id VARCHAR(64) PRIMARY KEY, kind VARCHAR(20) NOT NULL, category VARCHAR(60) NOT NULL,
 title VARCHAR(160) NOT NULL, body LONGTEXT NOT NULL, image VARCHAR(1000) NOT NULL, status VARCHAR(20) NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (id VARCHAR(64) PRIMARY KEY, value LONGTEXT NOT NULL);
CREATE TABLE IF NOT EXISTS accounts (id VARCHAR(64) PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (id VARCHAR(64) PRIMARY KEY, account_id VARCHAR(64) NOT NULL, expires_at BIGINT NOT NULL,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS rate_limits (id VARCHAR(64) PRIMARY KEY, hits INTEGER NOT NULL, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS sync_runs (id VARCHAR(64) PRIMARY KEY, status VARCHAR(20) NOT NULL, message VARCHAR(400) NOT NULL, created_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS schema_migrations (id VARCHAR(64) PRIMARY KEY);
